import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';
import { backendTestDatabase } from './backend-test-database';
import { PostgresRateLimiter } from '@/infrastructure/security/postgres-rate-limiter';
import { PrismaMatchingRepository } from '@/infrastructure/database/prisma/repositories/matching-repository';
import { PrismaJobRepository } from '@/infrastructure/database/prisma/repositories/job-repository';
import { PrismaJobSourceRepository } from '@/infrastructure/database/prisma/repositories/job-source-repository';
import { RunDailyJobPipeline } from '@/application/jobs/run-daily-job-pipeline';
import { CollectJobs } from '@/application/jobs/collect-jobs';
import { profileFixture, preferencesFixture } from '@/tests/fixtures/professional-data';
import type { CollectedJob } from '@/domain/jobs/collected-job';
describe.skipIf(process.env.JOBCOPILOT_DB_TESTS !== '1')('Backend operacional PostgreSQL isolado', () => {
    let db: Awaited<ReturnType<typeof backendTestDatabase>>;
    beforeAll(async () => { db = await backendTestDatabase(); }, 20000);
    afterAll(async () => { await db?.close(); });
    it('limiter distribui contagem entre instâncias concorrentes e expira buckets', async () => {
        const instances = [new PostgresRateLimiter(db.client), new PostgresRateLimiter(db.client)];
        const values = await Promise.all(Array.from({ length: 20 }, (_, index) => instances[index % 2].consume({ key: 'concurrency', limit: 5, windowMs: 60000 })));
        expect(values.filter((value) => value === 0)).toHaveLength(5);
        expect(values.filter((value) => value > 0)).toHaveLength(15);
        expect((await db.client.rateLimitBucket.findUniqueOrThrow({ where: { key: 'concurrency' } })).count).toBe(5);
        await db.client.rateLimitBucket.update({ where: { key: 'concurrency' }, data: { resetAt: new Date(0) } });
        expect(await instances[0].consume({ key: 'concurrency', limit: 5, windowMs: 60000 })).toBe(0);
    });
    it('limita cardinalidade sem gravar a chave excedente', async () => {
        await db.client.rateLimitBucket.deleteMany();
        await db.client.rateLimitBucket.createMany({ data: Array.from({ length: 10000 }, (_, index) => ({ key: 'fixture:' + index, count: 1, resetAt: new Date(Date.now() + 60000) })) });
        expect(await new PostgresRateLimiter(db.client).consume({ key: 'exceeded', limit: 5, windowMs: 60000 })).toBe(60);
        expect(await db.client.rateLimitBucket.count()).toBe(10000);
        await db.client.rateLimitBucket.deleteMany();
    });
    it('processa 10 usuários × 300 vagas, replay, checkpoint, falha parcial e lifecycle sem perder feedback', async () => {
        const users = await Promise.all(Array.from({ length: 10 }, (_, index) => db.client.user.create({ data: { email: 'scale' + index + '@example.com', passwordHash: 'synthetic-test-only', profile: { create: profileFixture }, preference: { create: preferencesFixture } } })));
        const repository = new PrismaMatchingRepository(db.client, db.schema);
        const jobs: CollectedJob[] = Array.from({ length: 300 }, (_, index) => ({ externalId: String(index), url: 'https://jobs.lever.co/ciandt/fixture-' + index, title: 'Pessoa desenvolvedora TypeScript pleno', company: 'Fixture', description: 'TypeScript', location: 'Remote Brazil', workModel: 'REMOTE' }));
        const collector = { collect: vi.fn(async () => jobs) };
        const collect = new CollectJobs({ source: { name: 'scale fixture', baseUrl: 'https://jobs.lever.co/ciandt' }, collector, repository: new PrismaJobRepository(db.client), sourceRepository: new PrismaJobSourceRepository(db.client) });
        const createPipeline = (signal?: AbortSignal) => new RunDailyJobPipeline({ repository, guard: { run: async (task) => task() }, collectors: [{ name: 'valid fixture', collect }, { name: 'failure fixture', collect: { execute: async () => { throw new Error('untrusted-body-token-test'); } } }] }).execute({ timeoutMs: 30000, signal });
        const first = await createPipeline();
        expect(first).toMatchObject({ usersProcessed: 10, matchesCreated: 3000, matchesUpdated: 0, partial: true, timedOut: false });
        expect(first?.sources[0]).toMatchObject({ inserted: 300, duplicates: 0, failed: false });
        expect(JSON.stringify(first)).not.toContain('untrusted-body');
        const match = await db.client.jobMatch.findFirstOrThrow({ where: { userId: users[0].id } });
        await db.client.matchFeedback.create({ data: { userId: users[0].id, jobMatchId: match.id, type: 'RELEVANT' } });
        const replay = await createPipeline();
        expect(replay).toMatchObject({ matchesCreated: 0, matchesUpdated: 3000 });
        expect(await db.client.jobMatch.count()).toBe(3000);
        const controller = new AbortController();
        const original = repository.persistBatch.bind(repository);
        const persist = vi.spyOn(repository, 'persistBatch').mockImplementation(async (...args) => { const counts = await original(...args); controller.abort(); return counts; });
        const stopped = await createPipeline(controller.signal);
        expect(stopped).toMatchObject({ partial: true, timedOut: true, matchesUpdated: 100 });
        expect(await repository.loadCheckpoint()).not.toBeNull();
        persist.mockRestore();
        const resumed = await createPipeline();
        expect(resumed).toMatchObject({ usersProcessed: 10, matchesCreated: 0, matchesUpdated: 2900 });
        expect(await repository.loadCheckpoint()).toBeNull();
        const source = await db.client.jobSource.findUniqueOrThrow({ where: { name: 'scale fixture' } });
        await db.client.job.update({ where: { id: match.jobId }, data: { lastSeenAt: new Date(Date.now() - 15 * 86400000) } });
        collector.collect.mockRejectedValueOnce(new Error('provider-failure'));
        await expect(collect.execute()).rejects.toThrow();
        expect((await db.client.job.findUniqueOrThrow({ where: { id: match.jobId } })).active).toBe(true);
        collector.collect.mockResolvedValueOnce([]);
        expect(await collect.execute()).toMatchObject({ deactivated: 1 });
        expect(await db.client.matchFeedback.count()).toBe(1);
        expect((await repository.listForUser(users[0].id, 1)).some((row) => row.id === match.id)).toBe(false);
        const refreshed = await collect.execute();
        expect(refreshed).toMatchObject({ inserted: 0, duplicates: 300, reactivated: 1 });
        expect((await db.client.job.findUniqueOrThrow({ where: { id: match.jobId } })).active).toBe(true);
        expect(await db.client.matchFeedback.count()).toBe(1);
        expect(await db.client.job.count({ where: { sourceId: source.id } })).toBe(300);
        console.info(JSON.stringify({ event: 'isolated_backend_scale', users: 10, jobs: 300, firstDurationMs: first?.durationMs, replayDurationMs: replay?.durationMs, resumedDurationMs: resumed?.durationMs }));
    }, 60000);
    it('não recomenda vagas sem observação há 30 dias mesmo durante falha permanente da fonte', async () => {
        const repository = new PrismaMatchingRepository(db.client, db.schema);
        const job = await db.client.job.findFirstOrThrow({ orderBy: { id: 'asc' } });
        const match = await db.client.jobMatch.findFirstOrThrow({ where: { jobId: job.id } });
        await db.client.jobMatch.updateMany({ where: { userId: match.userId }, data: { score: 0 } });
        await db.client.jobMatch.update({ where: { id: match.id }, data: { score: 100 } });
        expect((await repository.listForUser(match.userId, 1)).some((row) => row.id === match.id)).toBe(true);
        expect((await repository.listJobs()).some((row) => row.id === job.id)).toBe(true);
        await db.client.job.update({ where: { id: job.id }, data: { lastSeenAt: new Date(Date.now() - 31 * 86400000) } });
        expect((await repository.listForUser(match.userId, 1)).some((row) => row.id === match.id)).toBe(false);
        expect((await repository.listJobs()).some((row) => row.id === job.id)).toBe(false);
        expect(await db.client.matchFeedback.count()).toBe(1);
    });
    it('identidade ambígua não sobrescreve duas vagas existentes', async () => {
        const rows = await db.client.job.findMany({ take: 2, orderBy: { id: 'asc' } });
        const source = await db.client.jobSource.findUniqueOrThrow({ where: { id: rows[0].sourceId } });
        const collect = new CollectJobs({ source, sourceRepository: new PrismaJobSourceRepository(db.client), repository: new PrismaJobRepository(db.client), collector: { collect: async () => [{ externalId: rows[0].externalId!, url: rows[1].url, title: 'Ambiguous malicious update', company: 'Fixture', description: 'Synthetic fixture', location: 'Brazil' }] } });
        await expect(collect.execute()).rejects.toThrow('COLLECTION_INTERRUPTED');
        for (const row of rows) expect((await db.client.job.findUniqueOrThrow({ where: { id: row.id } })).title).toBe(row.title);
    });
});
